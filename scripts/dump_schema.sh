#!/usr/bin/env bash
# Regenerate scripts/sql/schema.sql, the empty schema a fresh install loads
# (scripts/init_db.py). Structure only: no rows, no DROP TABLE, and none of the
# source's schema_meta values (its crypto sentinel is tied to that APP_SECRET).
# Run after every schema change applied to fuse_dev:
#   sudo ./scripts/dump_schema.sh [schema]   (default fuse_dev)
set -euo pipefail
cd "$(dirname "$0")/.."
SCHEMA="${1:-fuse_dev}"
{
  echo "-- Fuse empty schema, generated by scripts/dump_schema.sh from $SCHEMA. Do not edit by hand."
  echo "SET FOREIGN_KEY_CHECKS=0;"
  mariadb-dump --no-data --compact --skip-add-drop-table --skip-comments "$SCHEMA" \
    | sed -E -e 's/ AUTO_INCREMENT=[0-9]+//' -e '/enable the sandbox mode/d'
  echo "SET FOREIGN_KEY_CHECKS=1;"
} > scripts/sql/schema.sql
echo "wrote scripts/sql/schema.sql ($(grep -c '^CREATE TABLE' scripts/sql/schema.sql) tables from $SCHEMA)"
